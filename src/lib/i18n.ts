export type TKey = keyof Dict
const dicts: Record<Lang, Dict> = { pl, en }

export const translate = (lang: Lang, key: TKey) => dicts[lang][key]

export function useT() {
  const lang = useGame((s) => s.profile?.settings.lang ?? s.guestLang)
  return (key: TKey) => dicts[lang][key]
}
